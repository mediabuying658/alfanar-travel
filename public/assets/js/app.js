/* Al Fanar Travel — global behaviour: navigation, consent, attribution, tracking, sticky CTA.
   Depends on window.AF_CONFIG (assets/js/config.js, generated by build.mjs from site.config.json). */
(function () {
  'use strict';
  var CFG = window.AF_CONFIG || {};
  var AF = (window.AF = window.AF || {});
  var REDUCE = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  /* ---------- safe storage ---------- */
  function store(kind) {
    try { var s = window[kind]; var k = '__af_t'; s.setItem(k, '1'); s.removeItem(k); return s; } catch (e) { return null; }
  }
  var LS = store('localStorage');
  var SS = store('sessionStorage');
  AF.get = function (s, k) { try { return s ? JSON.parse(s.getItem(k)) : null; } catch (e) { return null; } };
  AF.set = function (s, k, v) { try { if (s) s.setItem(k, JSON.stringify(v)); } catch (e) {} };
  AF.LS = LS; AF.SS = SS;

  /* ---------- dataLayer + tracking ---------- */
  window.dataLayer = window.dataLayer || [];
  function gtag() { window.dataLayer.push(arguments); }
  window.gtag = window.gtag || gtag;

  /* Push a tracking event. Never send personal form values (names, notes) here. */
  AF.track = function (event, params) {
    var payload = Object.assign({ event: event, page_service: document.body.dataset.service || 'home', page_path: location.pathname }, params || {});
    window.dataLayer.push(payload);
    if (CFG.debug) console.info('[AF track]', payload);
  };

  /* ---------- Consent (Google Consent Mode v2) ---------- */
  var CONSENT_KEY = 'af_consent_v1';
  gtag('consent', 'default', {
    ad_storage: 'denied', ad_user_data: 'denied', ad_personalization: 'denied',
    analytics_storage: 'denied', functionality_storage: 'granted', security_storage: 'granted',
    wait_for_update: 500
  });
  AF.consent = AF.get(LS, CONSENT_KEY); // {analytics:bool, ads:bool, ts}
  function applyConsent(c) {
    gtag('consent', 'update', {
      analytics_storage: c.analytics ? 'granted' : 'denied',
      ad_storage: c.ads ? 'granted' : 'denied',
      ad_user_data: c.ads ? 'granted' : 'denied',
      ad_personalization: c.ads ? 'granted' : 'denied'
    });
  }
  if (AF.consent) applyConsent(AF.consent);

  function loadGTM() {
    if (!CFG.gtmContainerId || window.__afGtm) return;
    window.__afGtm = true;
    window.dataLayer.push({ 'gtm.start': Date.now(), event: 'gtm.js' });
    var s = document.createElement('script');
    s.async = true; s.src = 'https://www.googletagmanager.com/gtm.js?id=' + encodeURIComponent(CFG.gtmContainerId);
    document.head.appendChild(s);
  }
  // GTM loads in all cases; Consent Mode keeps tags in cookieless/denied state until the user accepts.
  loadGTM();

  function initConsentBanner() {
    var el = document.getElementById('consent');
    if (!el) return;
    var open = function () { el.hidden = false; };
    if (!AF.consent) open();
    el.addEventListener('click', function (e) {
      var b = e.target.closest('[data-consent]');
      if (!b) return;
      var v = b.getAttribute('data-consent');
      var c = { analytics: v === 'all', ads: v === 'all', ts: new Date().toISOString() };
      AF.consent = c; AF.set(LS, CONSENT_KEY, c); applyConsent(c);
      if (REDUCE) { el.hidden = true; } else {
        el.classList.add('is-leaving');
        setTimeout(function () { el.hidden = true; el.classList.remove('is-leaving'); }, 300);
      }
      AF.track('consent_update', { consent_analytics: c.analytics, consent_ads: c.ads });
      captureAttribution(true);
    });
    document.querySelectorAll('[data-open-consent]').forEach(function (b) { b.addEventListener('click', open); });
  }

  /* ---------- Attribution (UTM + click IDs) ----------
     UTMs are non-personal campaign labels and are kept for the session.
     Click IDs (gclid/gbraid/wbraid) are ad identifiers: they are attached to a lead ONLY if ad consent was granted. */
  var ATTR_KEYS = ['utm_source', 'utm_medium', 'utm_campaign', 'utm_term', 'utm_content', 'utm_id'];
  var CLICK_KEYS = ['gclid', 'gbraid', 'wbraid'];
  function captureAttribution(consentChanged) {
    var q = new URLSearchParams(location.search);
    var hit = {};
    ATTR_KEYS.concat(CLICK_KEYS).forEach(function (k) { var v = q.get(k); if (v) hit[k] = v.slice(0, 200); });
    var has = Object.keys(hit).length > 0;
    var first = AF.get(SS, 'af_attr_first');
    if (!first) {
      first = Object.assign({ landing_page: location.pathname, referrer: document.referrer ? new URL(document.referrer).hostname : '', ts: new Date().toISOString() }, hit);
      AF.set(SS, 'af_attr_first', first);
    }
    if (has) AF.set(SS, 'af_attr_last', Object.assign({ landing_page: location.pathname, ts: new Date().toISOString() }, hit));
    // With ad consent, keep click IDs up to 90 days so a returning visitor's lead can still be matched for offline conversion import.
    if (AF.consent && AF.consent.ads) {
      var ids = {}; CLICK_KEYS.forEach(function (k) { if (hit[k]) ids[k] = hit[k]; });
      if (Object.keys(ids).length) AF.set(LS, 'af_click_ids', Object.assign(ids, { ts: Date.now() }));
    } else if (consentChanged && LS) { try { LS.removeItem('af_click_ids'); } catch (e) {} }
  }
  AF.getAttribution = function () {
    var first = AF.get(SS, 'af_attr_first') || {};
    var last = AF.get(SS, 'af_attr_last') || first;
    var strip = function (o) { var c = Object.assign({}, o); CLICK_KEYS.forEach(function (k) { delete c[k]; }); return c; };
    var out = { first_touch: strip(first), last_touch: strip(last) };
    if (AF.consent && AF.consent.ads) {
      var stored = AF.get(LS, 'af_click_ids');
      if (stored && Date.now() - stored.ts > 90 * 864e5) stored = null;
      var ids = {};
      CLICK_KEYS.forEach(function (k) { var v = last[k] || first[k] || (stored && stored[k]); if (v) ids[k] = v; });
      out.click_ids = ids;
    }
    return out;
  };

  /* ---------- WhatsApp helpers ---------- */
  AF.waUrl = function (text) {
    var n = String(CFG.whatsappNumber || '').replace(/\D/g, '');
    return 'https://wa.me/' + n + '?text=' + encodeURIComponent(text);
  };

  /* ---------- Navigation ---------- */
  function initNav() {
    var menuBtn = document.querySelector('.menu-btn');
    var nav = document.getElementById('site-nav');
    if (menuBtn && nav) {
      var header = document.querySelector('.site-header');
      var setMenu = function (open) {
        if (open) document.documentElement.style.setProperty('--nav-top', Math.max(0, header.getBoundingClientRect().bottom) + 'px');
        nav.classList.toggle('is-open', open);
        document.documentElement.classList.toggle('menu-open', open);
        menuBtn.setAttribute('aria-expanded', String(open));
        menuBtn.setAttribute('aria-label', open ? 'إغلاق القائمة' : 'فتح القائمة');
      };
      menuBtn.addEventListener('click', function () { setMenu(!nav.classList.contains('is-open')); });
      // close after choosing a link (e.g. «تواصل معنا» jumps within the page)
      nav.addEventListener('click', function (e) { if (e.target.closest('a')) setMenu(false); });
      document.addEventListener('keydown', function (e) {
        if (e.key === 'Escape' && nav.classList.contains('is-open')) { setMenu(false); menuBtn.focus(); }
      });
    }
    if (window.matchMedia('(hover: hover) and (min-width: 901px)').matches) {
      document.querySelectorAll('.nav__item').forEach(function (item) {
        var t = item.querySelector('.nav__toggle'); if (!t) return;
        var timer;
        item.addEventListener('mouseenter', function () { clearTimeout(timer); t.setAttribute('aria-expanded', 'true'); });
        item.addEventListener('mouseleave', function () { timer = setTimeout(function () { t.setAttribute('aria-expanded', 'false'); }, 160); });
      });
    }
    document.querySelectorAll('.nav__toggle').forEach(function (t) {
      t.addEventListener('click', function (e) {
        e.stopPropagation();
        var ex = t.getAttribute('aria-expanded') === 'true';
        t.setAttribute('aria-expanded', String(!ex));
      });
    });
    document.addEventListener('click', function (e) {
      document.querySelectorAll('.nav__toggle[aria-expanded="true"]').forEach(function (t) {
        if (!t.parentElement.contains(e.target) && window.matchMedia('(min-width: 901px)').matches) t.setAttribute('aria-expanded', 'false');
      });
    });
    document.addEventListener('keydown', function (e) {
      if (e.key !== 'Escape') return;
      document.querySelectorAll('.nav__toggle[aria-expanded="true"]').forEach(function (t) { t.setAttribute('aria-expanded', 'false'); t.focus(); });
    });
  }

  /* ---------- CTA tracking + scroll-to-form ---------- */
  function initCtas() {
    document.addEventListener('click', function (e) {
      var a = e.target.closest('[data-cta]');
      if (!a) return;
      AF.track('cta_click', { cta_location: a.getAttribute('data-cta') });
      var href = a.getAttribute('href') || '';
      if (href.charAt(0) === '#') {
        var target = document.querySelector(href);
        if (target) {
          e.preventDefault();
          target.scrollIntoView({ behavior: window.matchMedia('(prefers-reduced-motion: reduce)').matches ? 'auto' : 'smooth', block: 'start' });
          var first = target.querySelector('input:not([type=hidden]):not([disabled]), select, textarea');
          if (first) setTimeout(function () { first.focus({ preventScroll: true }); }, 450);
        }
      }
    });
    // Direct WhatsApp links (no form). Tracked separately and labelled as unqualified source.
    document.addEventListener('click', function (e) {
      var a = e.target.closest('[data-wa-direct]');
      if (!a) return;
      AF.track('whatsapp_open', { method: 'direct_link', cta_location: a.getAttribute('data-wa-direct'), lead_id: '' });
    });
  }

  /* ---------- Sticky mobile CTA hides while the form is visible ---------- */
  function initSticky() {
    var bar = document.querySelector('.sticky-cta');
    var form = document.querySelector('.form-card');
    if (!bar || !form || !('IntersectionObserver' in window)) return;
    new IntersectionObserver(function (entries) {
      entries.forEach(function (en) { bar.classList.toggle('is-hidden', en.isIntersecting); });
    }, { threshold: 0.15 }).observe(form);
  }

  /* ---------- FAQ engagement ---------- */
  function initFaq() {
    document.querySelectorAll('.faq details').forEach(function (d, i) {
      d.addEventListener('toggle', function () { if (d.open) AF.track('faq_open', { faq_index: i + 1 }); });
    });
  }

  /* Service tabs keep campaign parameters when the visitor switches category */
  /* Service tabs: remember it was a tab switch (skips intro animations on the next page) */
  document.addEventListener('click', function (e) {
    var a = e.target.closest('.svc-tabs a');
    if (!a || a.getAttribute('aria-current') === 'page') return;
    try { sessionStorage.setItem('af_nav', 'tab'); } catch (err) {}
    AF.track('service_tab_switch', { to: a.textContent.trim() });
  });
  function keepQuery() {
    if (!location.search) return;
    document.querySelectorAll('a[data-keep-query]').forEach(function (a) {
      if (a.getAttribute('aria-current') === 'page') return;
      var href = a.getAttribute('href'); if (href.indexOf('?') === -1) a.setAttribute('href', href.replace(/(#.*)?$/, location.search + '$1'));
    });
  }

  /* Destination cards: preselect the destination in the booking form, scroll to it, keep the choice visible.
     The value lands in the form field, so validation, the WhatsApp message and tracking all work unchanged. */
  function initQuickFill() {
    var cards = function () { return document.querySelectorAll('[data-fill]'); };
    function markSelected(value) {
      cards().forEach(function (c) {
        var on = c.getAttribute('data-fill').split('=').slice(1).join('=') === value;
        c.classList.toggle('is-selected', on);
        if (on) c.setAttribute('aria-current', 'true'); else c.removeAttribute('aria-current');
      });
    }
    document.addEventListener('click', function (e) {
      var b = e.target.closest('[data-fill]');
      if (!b) return;
      e.preventDefault();
      var parts = b.getAttribute('data-fill').split('=');
      var name = parts[0], value = parts.slice(1).join('=');
      var form = document.querySelector('form.lead-form');
      if (!form) return;
      var card = form.closest('.form-card');
      if (card && card.classList.contains('is-done')) { var ed = card.querySelector('[data-edit]'); if (ed) ed.click(); }
      var flex = form.elements.namedItem('destFlexible');
      if (flex && flex.checked) { flex.checked = false; flex.dispatchEvent(new Event('change', { bubbles: true })); }
      var el = form.elements.namedItem(name);
      if (el) { el.value = value; el.dispatchEvent(new Event('input', { bubbles: true })); el.dispatchEvent(new Event('change', { bubbles: true })); }
      markSelected(value);
      AF.track('destination_select', { destination: b.getAttribute('data-dest') || value, cta_location: 'destination_card' });
      var target = document.getElementById('booking');
      var smooth = !window.matchMedia('(prefers-reduced-motion: reduce)').matches;
      target.scrollIntoView({ behavior: smooth ? 'smooth' : 'auto', block: 'start' });
      // focus the next empty required field so the visitor continues the request
      setTimeout(function () {
        var next = Array.prototype.slice.call(form.querySelectorAll('.field[data-required]:not([hidden]) input:not([type=hidden]):not([type=checkbox]):not([type=radio]):not([disabled])')).filter(function (i) { return !i.value; })[0];
        (next || el).focus({ preventScroll: true });
      }, smooth ? 500 : 0);
    });
    // keep card state in sync if the visitor types a different destination
    document.addEventListener('input', function (e) {
      if (e.target.name !== 'destination' || !e.isTrusted) return;
      markSelected(e.target.value.trim());
    });
  }

  /* Smooth open/close for every <details> (FAQ + optional preferences) */
  function initDetails() {
    document.querySelectorAll('details').forEach(function (d) {
      var summary = d.querySelector('summary');
      if (!summary) return;
      var anim = null;
      summary.addEventListener('click', function (e) {
        if (REDUCE || !d.animate) return;
        e.preventDefault();
        if (anim) { anim.cancel(); anim = null; }
        var start = d.offsetHeight;
        var opening = !d.open || d.classList.contains('is-closing');
        d.style.overflow = 'hidden';
        if (opening) {
          d.classList.remove('is-closing');
          d.open = true;
          var end = d.offsetHeight;
          anim = d.animate([{ height: start + 'px' }, { height: end + 'px' }], { duration: 320, easing: 'cubic-bezier(.2,.7,.2,1)' });
          var body = d.querySelector('summary + *');
          if (body && body.animate) body.animate([{ opacity: 0, transform: 'translateY(-6px)' }, { opacity: 1, transform: 'none' }], { duration: 320, easing: 'ease-out' });
        } else {
          d.classList.add('is-closing');
          var endC = summary.offsetHeight + (d.offsetHeight - d.clientHeight);
          anim = d.animate([{ height: start + 'px' }, { height: endC + 'px' }], { duration: 260, easing: 'cubic-bezier(.4,0,.2,1)' });
        }
        anim.onfinish = function () {
          if (d.classList.contains('is-closing')) { d.open = false; d.classList.remove('is-closing'); }
          d.style.overflow = ''; anim = null;
        };
      });
    });
  }

  /* Subtle fade-up as sections enter the viewport */
  function initReveal() {
    if (REDUCE || !('IntersectionObserver' in window)) return;
    var sel = '.section-head, .step, .card, .dest-gallery > li, .trust__item, .faq details, .final-cta, .split > *, .hero-strip li, .checklist li, .cat, .collage .media, .faq-side, .tags li';
    var els = Array.prototype.slice.call(document.querySelectorAll(sel)).filter(function (el) { return !el.closest('.hero'); });
    document.documentElement.classList.add('reveal-on');
    els.forEach(function (el) {
      el.classList.add('reveal');
      var sibs = Array.prototype.filter.call(el.parentElement.children, function (c) { return c.matches(sel); });
      var i = sibs.indexOf(el);
      if (i > 0) el.style.setProperty('--d', Math.min(i, 6) * 0.07 + 's');
    });
    var io = new IntersectionObserver(function (entries) {
      entries.forEach(function (en) { if (en.isIntersecting) { en.target.classList.add('is-in'); io.unobserve(en.target); } });
    }, { rootMargin: '0px 0px -8% 0px', threshold: 0.08 });
    els.forEach(function (el) {
      // anything already above the fold is shown immediately
      if (el.getBoundingClientRect().top < window.innerHeight * 0.92) el.classList.add('is-in'); else io.observe(el);
    });
  }

  /* keep the page offset equal to the fixed header's real height */
  function initHeaderOffset() {
    var h = document.querySelector('.site-header');
    if (!h) return;
    var set = function () { document.documentElement.style.setProperty('--hdr-h', h.offsetHeight + 'px'); };
    set();
    if ('ResizeObserver' in window) new ResizeObserver(set).observe(h); else window.addEventListener('resize', set);
  }

  document.addEventListener('DOMContentLoaded', function () {
    initHeaderOffset(); initDetails(); initReveal();
    keepQuery(); initQuickFill();
    captureAttribution(false);
    initNav(); initConsentBanner(); initCtas(); initSticky(); initFaq();
    AF.track('page_view_service', { lp_variant: document.body.dataset.variant || 'a' });
  });
})();
