#!/usr/bin/env node
/* Static build — no dependencies.
   node build.mjs            → dist/     (production: clean URLs /hotels, /flights/umrah …, for Vercel/Netlify/any static host)
   node build.mjs --preview  → preview/  (relative links to folder/index.html, works from file:// or any sub-path)
*/
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { makeCtx, layout } from './src/ui.mjs';
import * as P from './src/pages.mjs';

const root = path.dirname(fileURLToPath(import.meta.url));
const cfg = JSON.parse(fs.readFileSync(path.join(root, 'site.config.json'), 'utf8'));
const preview = process.argv.includes('--preview');
const mode = preview ? 'preview' : 'prod';
const out = path.join(root, preview ? 'preview' : 'dist');

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
fs.cpSync(path.join(root, 'public'), out, { recursive: true });

// runtime config (only public, non-secret values)
const runtime = {
  brandNameAr: cfg.brand.nameAr,
  whatsappNumber: (cfg.contact.whatsappNumber || '').replace(/\D/g, ''),
  whatsappDisplay: cfg.contact.whatsappDisplay || '',
  leadEndpoint: preview ? '' : cfg.integrations.leadEndpoint,
  gtmContainerId: preview ? '' : cfg.integrations.gtmContainerId,
  autoOpenWhatsApp: true,
  debug: !!cfg.showPlaceholders
};
fs.writeFileSync(path.join(out, 'assets/js/config.js'), `/* generated by build.mjs from site.config.json — do not edit by hand */\nwindow.AF_CONFIG = ${JSON.stringify(runtime, null, 2)};\n`);

const pages = [
  ['/', P.home], ['/hotels', P.hotels], ['/flights', P.flights], ['/flights/honeymoon', P.honeymoon],
  ['/flights/umrah', P.umrah], ['/privacy', P.privacy], ['/terms', P.terms], ['/404', P.notFound]
];
const built = [];
for (const [route, fn] of pages) {
  const ctx = makeCtx({ cfg, mode, route: route === '/404' ? '/' : route, root });
  const { page, body } = fn(ctx);
  const html = layout(ctx, page, body);
  const file = route === '/' ? 'index.html' : route === '/404' ? '404.html' : route.slice(1) + '/index.html';
  fs.mkdirSync(path.dirname(path.join(out, file)), { recursive: true });
  fs.writeFileSync(path.join(out, file), html);
  built.push({ route, file, noindex: page.noindex, bytes: Buffer.byteLength(html) });
}

if (!preview) {
  const base = cfg.siteUrl.replace(/\/$/, '');
  const urls = built.filter((b) => !b.noindex && b.route !== '/404').map((b) => `  <url><loc>${base}${b.route === '/' ? '/' : b.route}</loc></url>`).join('\n');
  fs.writeFileSync(path.join(out, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`);
  fs.writeFileSync(path.join(out, 'robots.txt'), cfg.showPlaceholders
    ? 'User-agent: *\nDisallow: /\n# pre-launch build (showPlaceholders=true)\n'
    : `User-agent: *\nAllow: /\nSitemap: ${base}/sitemap.xml\n`);
}

// Warn about anything still pending approval
const missing = [];
if (!cfg.contact.whatsappNumber) missing.push('contact.whatsappNumber (verified WhatsApp Business number)');
if (!cfg.brand.logoFile) missing.push('brand.logoFile (official logo)');
if (cfg.siteUrl.includes('REPLACE')) missing.push('siteUrl (production domain for canonical tags)');
if (!cfg.integrations.gtmContainerId) missing.push('integrations.gtmContainerId');
['commercialRegistration', 'tourismLicense'].forEach((k) => { if (!cfg.licensing[k]) missing.push('licensing.' + k); });
['phoneDisplay', 'workingHoursAr'].forEach((k) => { if (!cfg.contact[k]) missing.push('contact.' + k); });
if (!cfg.integrations.privacyPolicyApproved) missing.push('integrations.privacyPolicyApproved (legal review)');
const imgs = ['hotels/hero-room', 'hotels/lobby', 'hotels/breakfast', 'flights/hero-airport', 'honeymoon/hero-resort', 'umrah/hero-kaaba-golden-hour']
  .filter((f) => !fs.existsSync(path.join(root, 'public/assets/img', f + '.jpg')));
if (imgs.length) missing.push('licensed images: ' + imgs.map((f) => f + '.jpg').join(', '));

console.log(`Built ${built.length} pages → ${path.relative(root, out)}/ (${mode})`);
built.forEach((b) => console.log(`  ${b.route.padEnd(20)} ${b.file.padEnd(32)} ${(b.bytes / 1024).toFixed(1)} KB${b.noindex ? '  noindex' : ''}`));
if (missing.length) { console.log('\n⚠ Pending client approval / configuration:'); missing.forEach((m) => console.log('  - ' + m)); }
if (!cfg.showPlaceholders && missing.length) { console.error('\n✖ showPlaceholders=false but required items are missing. Refusing production build.'); process.exit(1); }
